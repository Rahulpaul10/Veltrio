import { ArrowLeft, CheckCircle2, Clock, Download, ExternalLink, Printer, SearchX, XCircle } from 'lucide-react'
import { Card, CopyButton, EmptyState, ErrorState, GhostButton, Notice, Skeleton } from '@/components/ui'
import { LogoMark } from '@/components/Logo'
import { Link } from '@/veltrio/router'
import { ACTIVE_CHAIN_ID, IS_TESTNET, NETWORK_LABEL, txUrl } from '@/veltrio/network'
import { StalePending } from '@/components/StalePending'
import { useWallet } from '@/veltrio/wallet'
import { useReceiptData, type ReceiptData } from '@/veltrio/receiptData'
import { useAllTrackedTxs } from '@/veltrio/txStore'
import { fmtAmount, fmtDateTime, fmtFee } from '@/veltrio/format'
import { findContact, useContacts } from '@/veltrio/contacts'

function typeLabel(data: ReceiptData, me: string | undefined): string {
  if (data.kind === 'transfer') {
    const lower = me?.toLowerCase()
    if (lower && data.payee?.toLowerCase() === lower && data.payer?.toLowerCase() !== lower) return 'USDC received'
    if (lower && data.payer?.toLowerCase() === lower) return 'USDC sent'
    return 'USDC transfer'
  }
  if (data.amount) return `Contract call${data.method ? `: ${data.method}` : ''} (moves USDC)`
  return `Contract call${data.method ? `: ${data.method}` : ''}`
}

const STATUS = {
  success: { label: 'Confirmed', color: 'var(--success)', Icon: CheckCircle2 },
  failed: { label: 'Failed', color: 'var(--danger)', Icon: XCircle },
  pending: { label: 'Pending', color: 'var(--warn)', Icon: Clock },
} as const

function buildText(data: ReceiptData, me: string | undefined): string {
  const lines = [
    'VELTRIO TRANSACTION RECEIPT',
    `Network: ${NETWORK_LABEL} (chain ${ACTIVE_CHAIN_ID}${IS_TESTNET ? ', testnet' : ''})`,
    `Status: ${STATUS[data.status].label}`,
    `Type: ${typeLabel(data, me)}`,
    `Amount: ${data.amount ? `${fmtAmount(data.amount)} USDC` : 'Not applicable'}`,
    `From: ${data.payer ?? data.sender}`,
    `To: ${data.payee ?? 'Unavailable'}`,
    `Transaction hash: ${data.hash}`,
    `Date and time: ${data.timestamp ? fmtDateTime(data.timestamp) : 'Unavailable until confirmed'}`,
    `${data.feeKind === 'confirmed' ? 'Network fee (confirmed)' : 'Network fee (estimated maximum, not final)'}: ${data.fee ? `${fmtFee(data.fee)} USDC` : 'Unavailable'}`,
    `Explorer: ${txUrl(data.hash)}`,
    '',
    'Generated by Veltrio from public onchain data.',
  ]
  return lines.join('\n')
}

function download(data: ReceiptData, me: string | undefined) {
  const blob = new Blob([buildText(data, me)], { type: 'text/plain;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `veltrio-receipt-${data.hash.slice(2, 10)}.txt`
  a.click()
  URL.revokeObjectURL(url)
}

function Line({ label, children, mono }: { label: string; children: React.ReactNode; mono?: boolean }) {
  return (
    <div className="flex flex-col gap-0.5 py-3 sm:flex-row sm:items-start sm:justify-between sm:gap-6">
      <dt className="shrink-0 text-sm" style={{ color: 'var(--muted)' }}>{label}</dt>
      <dd className={`min-w-0 break-all text-sm font-medium sm:text-right ${mono ? 'mono text-xs leading-relaxed' : 'tabular-nums'}`}>{children}</dd>
    </div>
  )
}

export function Receipt({ hash }: { hash: string }) {
  const { address } = useWallet()
  const contacts = useContacts()
  const tracked = useAllTrackedTxs()
  const { data, isLoading, isError, refetch } = useReceiptData(hash)
  const validHash = /^0x[0-9a-fA-F]{64}$/.test(hash)
  const local = tracked.find((t) => t.hash.toLowerCase() === hash.toLowerCase())

  const back = (
    <Link to="/transactions" className="no-print mb-4 inline-flex min-h-10 items-center gap-2 text-sm font-semibold" style={{ color: 'var(--accent)' }}>
      <ArrowLeft className="size-4" aria-hidden /> Transactions
    </Link>
  )

  if (!validHash) {
    return <>{back}<Card><ErrorState title="Invalid transaction hash" body="A transaction hash starts with 0x followed by 64 hexadecimal characters." /></Card></>
  }
  if (isLoading) return <>{back}<Skeleton className="h-96 w-full rounded-3xl" /></>
  if (isError) {
    return <>{back}<Card><ErrorState title="Could not load this transaction" body={`The ${NETWORK_LABEL} RPC did not respond. Check your connection and retry.`} onRetry={() => void refetch()} /></Card></>
  }
  if (!data) {
    return (
      <>
        {back}
        <Card>
          {local ? (
            <>
              <EmptyState icon={<Clock className="size-5" aria-hidden />} title="Waiting for the network" body="This transaction was submitted from your wallet but the RPC node has not reported it yet. This page updates automatically." />
              <StalePending hash={hash} />
            </>
          ) : (
            <EmptyState icon={<SearchX className="size-5" aria-hidden />} title="Transaction not found" body={`No transaction with this hash exists on ${NETWORK_LABEL}. It may be on another network.`} />
          )}
        </Card>
      </>
    )
  }

  const s = STATUS[data.status]
  const payerLabel = findContact(contacts, data.payer ?? data.sender)?.label
  const payeeLabel = findContact(contacts, data.payee ?? undefined)?.label

  return (
    <>
      {back}
      <div className="mx-auto max-w-xl">
        <article id="receipt-sheet" className="glass overflow-hidden rounded-3xl">
          <div className="h-1" style={{ background: 'linear-gradient(90deg, #4f8cff, #2dd4e6)' }} />
          <div className="p-5 sm:p-7">
            <header className="flex items-center justify-between">
              <div className="flex items-center gap-2.5">
                <LogoMark size={30} />
                <div>
                  <div className="display text-lg font-bold leading-none">Veltrio</div>
                  <div className="mt-1 text-xs" style={{ color: 'var(--muted)' }}>Transaction receipt</div>
                </div>
              </div>
              <span className="inline-flex items-center gap-1.5 rounded-full px-3 py-1.5 text-sm font-semibold" style={{ color: s.color, background: 'rgba(255,255,255,0.06)' }}>
                <s.Icon className="size-4" aria-hidden /> {s.label}
              </span>
            </header>

            <div className="mt-6 text-center">
              <div className="text-xs font-semibold uppercase tracking-widest" style={{ color: 'var(--subtle)' }}>{typeLabel(data, address)}</div>
              {data.amount ? (
                <div className="display mt-1 text-5xl font-bold tabular-nums" style={{ textDecoration: data.status === 'failed' ? 'line-through' : undefined }}>
                  {fmtAmount(data.amount)} <span className="text-xl" style={{ color: 'var(--subtle)' }}>USDC</span>
                </div>
              ) : (
                <div className="display mt-1 text-2xl font-bold" style={{ color: 'var(--muted)' }}>No USDC amount</div>
              )}
              <p className="mx-auto mt-2 max-w-sm text-pretty text-sm" style={{ color: 'var(--muted)' }}>
                {data.status === 'pending' && 'Not yet confirmed. This receipt is not final until the network includes the transaction.'}
                {data.status === 'failed' && 'This transaction reverted. No USDC was moved. The network fee was still charged.'}
                {data.status === 'success' && `Confirmed on ${NETWORK_LABEL}.`}
              </p>
            </div>

            <dl className="mt-5 divide-y" style={{ borderColor: 'var(--border)' }}>
              <Line label="From" mono>{payerLabel ? `${payerLabel} · ` : ''}{data.payer ?? data.sender}</Line>
              <Line label="To" mono>{data.payee ? `${payeeLabel ? `${payeeLabel} · ` : ''}${data.payee}` : 'Unavailable'}</Line>
              <Line label="Transaction hash" mono>{data.hash}</Line>
              <Line label="Date and time">{data.timestamp ? fmtDateTime(data.timestamp) : 'Unavailable until confirmed'}</Line>
              <Line label="Network">{NETWORK_LABEL} · chain {ACTIVE_CHAIN_ID}{IS_TESTNET ? ' · testnet' : ''}</Line>
              {data.blockNumber !== null && <Line label="Block">{data.blockNumber.toLocaleString()}</Line>}
              <Line label={data.feeKind === 'confirmed' ? 'Network fee (confirmed)' : 'Network fee (estimated maximum)'}>
                {data.fee ? `${fmtFee(data.fee)} USDC` : 'Unavailable'}
                {data.feeKind === 'estimated' && <span className="mt-0.5 block text-xs font-normal" style={{ color: 'var(--subtle)' }}>Estimate only. The confirmed fee is set once the transaction is included.</span>}
                {data.feeKind === 'confirmed' && <span className="mt-0.5 block text-xs font-normal" style={{ color: 'var(--subtle)' }}>Paid by the sender, in USDC.</span>}
              </Line>
            </dl>

            <footer className="mt-4 text-center text-xs text-pretty" style={{ color: 'var(--subtle)' }}>
              Generated by Veltrio from public onchain data.{IS_TESTNET ? ' Test network only: these funds have no real-world value.' : ''}
            </footer>
          </div>
        </article>

        {data.status === 'pending' && <div className="no-print"><StalePending hash={data.hash} /></div>}
        {data.kind === 'contract' && <Notice tone="info" className="no-print mt-4">This was a contract interaction, not a direct USDC transfer, so it is not counted in sent or received totals.</Notice>}

        <div className="no-print mt-4 grid grid-cols-2 gap-3">
          <CopyButton text={data.hash} label="Copy hash" message="Transaction hash copied" className="!min-h-12 w-full" />
          <a href={txUrl(data.hash)} target="_blank" rel="noopener noreferrer" className="glass inline-flex min-h-12 items-center justify-center gap-2 rounded-2xl text-sm font-semibold hover:bg-white/10">
            Arc Explorer <ExternalLink className="size-4" aria-hidden />
          </a>
          <GhostButton className="!min-h-12" onClick={() => window.print()}><Printer className="size-4" aria-hidden /> Print / Save PDF</GhostButton>
          <GhostButton className="!min-h-12" onClick={() => download(data, address)}><Download className="size-4" aria-hidden /> Download</GhostButton>
        </div>
      </div>
    </>
  )
}
